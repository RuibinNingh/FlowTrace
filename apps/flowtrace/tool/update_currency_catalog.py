"""Generate the Dart catalog from the repository's frozen ISO fixture."""

import json
from pathlib import Path


def main() -> None:
    root = Path(__file__).resolve().parents[3]
    catalog = json.loads(
        (root / "contracts/fixtures/assets/catalogs.json").read_text(encoding="utf-8")
    )["currency_catalog"]
    server = json.loads(
        (root / "server/src/flowtrace_server/currencies/data/iso4217.json").read_text(
            encoding="utf-8"
        )
    )
    assert catalog == {k: v for k, v in server.items() if k != "source_sha256"}

    def literal(value: str) -> str:
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("$", r"\$") + "'"

    source = "/// Frozen ISO 4217 numeric minor units, shared with the server.\n"
    source += "/// Generated by tool/update_currency_catalog.py from the frozen fixture.\n"
    for name, key in [
        ("currencyCatalogDate", "catalog_date"),
        ("currencyCatalogSource", "source"),
        ("currencyCatalogSourceSha256", "source_sha256"),
    ]:
        source += f"const {name} = {literal(server[key])};\n"
    source += "\nconst currencyScales = <String, int>{\n"
    source += "".join(
        f"  {literal(row['code'])}: {row['scale']},\n" for row in catalog["currencies"]
    )
    source += "};\n\nconst currencyNames = <String, String>{\n"
    source += "".join(
        f"  {literal(row['code'])}: {literal(row['name'])},\n"
        for row in catalog["currencies"]
    )
    source += "};\n"
    (root / "apps/flowtrace/lib/core/money/currency_catalog.dart").write_text(
        source, encoding="utf-8"
    )
    print(f"Generated {len(catalog['currencies'])} frozen currencies.")


if __name__ == "__main__":
    main()
